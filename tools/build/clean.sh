#!/bin/bash

# Verify directory
WORKSPACE_DIR=$FLYCHAMS_PATH/ros2_ws
if [ ! -d "$WORKSPACE_DIR" ]; then
    echo "❌ Directory $WORKSPACE_DIR was not found."
    exit 1
fi

cd "$WORKSPACE_DIR" || { echo "❌ Failed to navigate to $WORKSPACE_DIR"; exit 1; }

echo ""
echo ""
echo ""
echo "============================================================================================"
echo "============================================================================================"
echo "🚀 CLEANING WORKSPACE"
echo "============================================================================================"
echo "============================================================================================"
echo ""
echo ""
echo ""

# Clean build, install and log directories
rm -rf build/ install/ log/ || { 
        echo ""
        echo "============================================================================================"
        echo "❌ Failed to clean build, install and log directories."
        echo "============================================================================================"
        echo ""
        exit 1
    }

echo ""
echo ""
echo ""
echo "============================================================================================"
echo "============================================================================================"
echo "✅ WORKSPACE CLEANED SUCCESSFULLY"
echo "============================================================================================"
echo "============================================================================================"
echo ""
echo ""
echo ""